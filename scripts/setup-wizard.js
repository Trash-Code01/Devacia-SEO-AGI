#!/usr/bin/env node

/**
 * Devacia SEO AGI — Interactive Setup & Onboarding Wizard
 * 
 * Quickly configures:
 * 1. Target Website URL & SEO Domains
 * 2. Google OAuth 2.0 Credentials (GSC, GA4, GBP, GKP)
 * 3. Environment Variables (.env generation)
 * 4. Model Context Protocol (MCP) configuration for Antigravity, Claude, Cursor, Windsurf
 */

import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { fileURLToPath } from 'url';
import './env-loader.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const ANSI = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  cyan: '\x1b[36m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  red: '\x1b[31m',
  magenta: '\x1b[35m',
  dim: '\x1b[2m',
};

function banner() {
  console.log(`
${ANSI.cyan}${ANSI.bold}╔══════════════════════════════════════════════════════════════════════╗
║               DEVACIA SEO AGI — ONBOARDING & SETUP WIZARD            ║
║         Configure your Site, Google APIs & Agent MCP Integration     ║
╚══════════════════════════════════════════════════════════════════════╝${ANSI.reset}
`);
}

function ask(rl, question, defaultVal = '') {
  return new Promise((resolve) => {
    const prompt = defaultVal ? `${question} [${ANSI.dim}${defaultVal}${ANSI.reset}]: ` : `${question}: `;
    rl.question(prompt, (answer) => {
      resolve(answer.trim() || defaultVal);
    });
  });
}

async function main() {
  banner();

  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  console.log(`${ANSI.bold}Step 1: Target Website & SEO Domain Configuration${ANSI.reset}`);
  console.log(`${ANSI.dim}Enter the primary website domain you want to audit, inspect, and optimize.${ANSI.reset}\n`);

  const currentSite = process.env.SEO_SITE_URL || 'https://www.devacia.com';
  const siteUrl = await ask(rl, 'Primary Website URL', currentSite);

  console.log(`\n${ANSI.bold}Step 2: Google Analytics 4 (GA4) Configuration${ANSI.reset}`);
  console.log(`${ANSI.dim}Enter your numeric GA4 Property ID (found in GA4 → Admin → Property Settings).${ANSI.reset}\n`);

  const currentGa4 = process.env.GA4_PROPERTY_ID || '538121325';
  const ga4PropId = await ask(rl, 'GA4 Property ID', currentGa4);

  console.log(`\n${ANSI.bold}Step 3: Google Business Profile (Local SEO) Details${ANSI.reset}`);
  console.log(`${ANSI.dim}Enter details for localized NAP audits (Name, Address, Phone).${ANSI.reset}\n`);

  const bizName = await ask(rl, 'Business Name', process.env.GBP_BUSINESS_NAME || 'Devacia');
  const bizPhone = await ask(rl, 'Business Phone', process.env.GBP_PHONE || '+91 63069 40734');
  const bizCity = await ask(rl, 'Primary City/Metro', process.env.GBP_CITY || 'Prayagraj');
  const bizCountry = await ask(rl, 'Country', process.env.GBP_COUNTRY || 'India');

  console.log(`\n${ANSI.bold}Step 4: Google Ads API / Keyword Planner (Optional)${ANSI.reset}`);
  console.log(`${ANSI.dim}Leave blank to use free zero-auth real-time Google Autocomplete & Suggest algorithms.${ANSI.reset}\n`);

  const adsDevToken = await ask(rl, 'Google Ads Developer Token (optional)', process.env.GOOGLE_ADS_DEVELOPER_TOKEN || '');
  const adsCustId = await ask(rl, 'Google Ads Customer ID (optional)', process.env.GOOGLE_ADS_CUSTOMER_ID || '');

  rl.close();

  // Write or update .env
  const envPath = path.resolve(ROOT_DIR, '.env');
  const envContent = `# =============================================================================
# Devacia SEO AGI Configuration
# Generated by npm run setup on ${new Date().toISOString()}
# =============================================================================

# Primary Target Website
SEO_SITE_URL=${siteUrl}
GSC_SITE_URL=${siteUrl}

# Google Analytics 4
GA4_PROPERTY_ID=${ga4PropId}

# Google Business Profile (Local SEO)
GBP_BUSINESS_NAME="${bizName}"
GBP_PHONE="${bizPhone}"
GBP_CITY="${bizCity}"
GBP_COUNTRY="${bizCountry}"
GBP_WEBSITE=${siteUrl}

# Google Keyword Planner / Google Ads API (Optional)
GOOGLE_ADS_DEVELOPER_TOKEN=${adsDevToken}
GOOGLE_ADS_CUSTOMER_ID=${adsCustId}
`;

  fs.writeFileSync(envPath, envContent, 'utf-8');
  console.log(`\n${ANSI.green}✓ Configuration successfully saved to .env!${ANSI.reset}\n`);

  // Check OAuth files
  console.log(`${ANSI.bold}=== Google Cloud OAuth 2.0 Credentials Check ===${ANSI.reset}`);
  const hasUnified = fs.existsSync(path.resolve(ROOT_DIR, 'google-oauth.json'));
  const hasGsc = fs.existsSync(path.resolve(ROOT_DIR, 'gsc-oauth.json'));
  const hasGa4 = fs.existsSync(path.resolve(ROOT_DIR, 'ga4-oauth.json'));
  const hasGbp = fs.existsSync(path.resolve(ROOT_DIR, 'gbp-oauth.json'));

  if (hasUnified) {
    console.log(`  ${ANSI.green}✓ Found unified google-oauth.json!${ANSI.reset} (Covers GSC, GA4, GBP, and GKP)`);
  } else {
    console.log(`  • google-oauth.json: ${hasUnified ? ANSI.green + '✓ Found' : ANSI.yellow + 'Not present (Tip: one unified file can power all 4 APIs)'}${ANSI.reset}`);
    console.log(`  • gsc-oauth.json:    ${hasGsc ? ANSI.green + '✓ Found' : ANSI.red + '✗ Missing'}${ANSI.reset}`);
    console.log(`  • ga4-oauth.json:    ${hasGa4 ? ANSI.green + '✓ Found' : ANSI.red + '✗ Missing'}${ANSI.reset}`);
    console.log(`  • gbp-oauth.json:    ${hasGbp ? ANSI.green + '✓ Found' : ANSI.red + '✗ Missing'}${ANSI.reset}`);
  }

  console.log(`\n${ANSI.bold}=== Next Steps ===${ANSI.reset}`);
  console.log(`1. Place your OAuth 2.0 Desktop Client JSON as ${ANSI.cyan}google-oauth.json${ANSI.reset} in the project root.`);
  console.log(`2. Authenticate the APIs with 1-click in your terminal:`);
  console.log(`   ${ANSI.yellow}npm run gsc:auth${ANSI.reset}   -> Authenticates Google Search Console`);
  console.log(`   ${ANSI.yellow}npm run ga4:auth${ANSI.reset}   -> Authenticates Google Analytics 4`);
  console.log(`   ${ANSI.yellow}npm run gbp:auth${ANSI.reset}   -> Authenticates Google Business Profile`);
  console.log(`3. Start the Master MCP Server or use directly from your terminal:`);
  console.log(`   ${ANSI.green}npm run mcp${ANSI.reset}        -> Stdio Model Context Protocol Server`);
  console.log(`   ${ANSI.green}npm run start${ANSI.reset}      -> Subsystem health check\n`);
}

main().catch((err) => {
  console.error('Setup error:', err.message);
  process.exit(1);
});
